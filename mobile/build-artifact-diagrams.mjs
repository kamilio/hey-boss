import {build} from 'esbuild';
import {appendFileSync,existsSync,readFileSync,writeFileSync,mkdirSync,rmSync} from 'node:fs';
import {dirname,resolve,join,relative} from 'node:path';
const outdir=new URL('../src/issues/web/',import.meta.url).pathname;
const outfile=join(outdir,'artifact-diagrams.js');
// Keep the common loader small. Fetch diagram-specific parsers on demand.
const result=await build({entryPoints:[new URL('./artifact-diagrams.mjs',import.meta.url).pathname],outdir,bundle:true,minify:true,format:'esm',splitting:true,chunkNames:'diagram-assets/[name]-[hash]',target:['safari16','chrome100'],legalComments:'eof',metafile:true,write:false});
rmSync(join(outdir,'diagram-assets'),{recursive:true,force:true});
for(const file of result.outputFiles){mkdirSync(dirname(file.path),{recursive:true});writeFileSync(file.path,file.contents);}
const chunks=result.outputFiles.filter(file=>file.path!==outfile).map(file=>relative(outdir,file.path)).sort();
writeFileSync(join(outdir,'diagram-assets.rs'),'// Generated by mobile/build-artifact-diagrams.mjs.\n&[\n'+chunks.map(name=>'    ("/'+name+'", include_bytes!("'+name+'")),').join('\n')+'\n]\n');
const packages=new Set();
for(const input of Object.keys(result.metafile.inputs)){
 if(!input.includes('node_modules/'))continue;
 let directory=dirname(resolve(input));
 while(!existsSync(join(directory,'package.json'))||!JSON.parse(readFileSync(join(directory,'package.json'),'utf8')).name)directory=dirname(directory);
 packages.add(directory);
}
for(const directory of [...packages].sort()){
 const info=JSON.parse(readFileSync(join(directory,'package.json'),'utf8'));
 const license=['LICENSE','LICENSE.md','LICENSE.txt','license','license.md','license.txt','LICENSE-MIT','COPYING'].map(name=>join(directory,name)).find(existsSync);
 const readme=join(directory,'README.md');
 const text=license?readFileSync(license,'utf8'):existsSync(readme)?readFileSync(readme,'utf8').match(/^## License\s*\n([\s\S]*)/m)?.[1]:null;
 if(!text)throw Error('Missing bundled license: '+info.name);
 appendFileSync(outfile,'\n/*! '+info.name+' '+info.version+'\n'+text.replaceAll('*/','* /')+' */\n');
}
