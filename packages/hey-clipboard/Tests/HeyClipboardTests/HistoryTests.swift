import AppKit
import XCTest
@testable import HeyClipboard

final class HistoryTests: XCTestCase {
    private var directory: URL!
    private var history: History!
    private var board: NSPasteboard!
    override func setUpWithError() throws {
        directory = URL(fileURLWithPath: FileManager.default.currentDirectoryPath).appendingPathComponent(".build/clipboard-test-" + UUID().uuidString)
        history = try History(directory: directory)
        board = NSPasteboard.withUniqueName()
    }
    override func tearDownWithError() throws {
        history.finishWrites()
        board.releaseGlobally()
        try FileManager.default.removeItem(at: directory)
    }
    func testTemporaryDictationAndRestorationNeverEnterHistory() {
        board.setString("user copy", forType: .string)
        let monitor = ClipboardMonitor(history: history, board: board)
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            let item = NSPasteboardItem()
            item.setString("private dictation", forType: .string)
            item.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
            board.clearContents(); board.writeObjects([item])
            monitor.poll(app: "Hey Talk")
            board.clearContents(); board.setString("user copy", forType: .string)
            monitor.poll(app: "T3")
        }
        XCTAssertTrue(history.clips.isEmpty)
        XCTAssertEqual(monitor.skipped, 4)
        board.clearContents(); board.setString("new user copy 🌍\nline 2", forType: .string)
        monitor.poll(app: "T3")
        XCTAssertEqual(history.clips.map(\.text), ["new user copy 🌍\nline 2"])
    }
    func testMarkerOnSecondItemAlsoExcludesText() {
        let monitor = ClipboardMonitor(history: history, board: board)
        let text = NSPasteboardItem(), marker = NSPasteboardItem()
        text.setString("private", forType: .string)
        marker.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        board.writeObjects([text, marker]); monitor.poll(app: "Password manager")
        XCTAssertTrue(history.clips.isEmpty)
    }
    func testDeduplicationPinsRetentionAndPersistence() throws {
        let pinned = try XCTUnwrap(history.add("pinned", app: "App"))
        history.pin(pinned.id, true)
        for index in 0..<45 { history.add("entry \(index)", app: "App") }
        XCTAssertEqual(history.clips.count, 41)
        XCTAssertTrue(history.clips.contains { $0.id == pinned.id })
        let oldID = history.clips.first!.id
        history.add("entry 44", app: "App")
        XCTAssertEqual(history.clips.count, 41)
        XCTAssertEqual(history.clips.first?.id, oldID)
        history.finishWrites()
        let restored = try History(directory: directory)
        XCTAssertEqual(restored.clips, history.clips)
        XCTAssertEqual(restored.matching("ENTRY 44").count, 1)
        XCTAssertEqual(restored.matching("app").count, 41)
        let permissions = try FileManager.default.attributesOfItem(atPath: directory.appendingPathComponent("history.json").path)[.posixPermissions] as? Int
        XCTAssertEqual(permissions, 0o600)
    }
    func testFlycutMigrationIsIdempotentAndPreservesFavorites() throws {
        let data = try PropertyListSerialization.data(fromPropertyList: ["store": [
            "jcList": [["Contents": "newest", "AppLocalizedName": "Safari", "Timestamp": 1234], ["Contents": "older"]],
            "favoritesList": [["Contents": "older"], ["Contents": "favorite"]]
        ]], format: .binary, options: 0)
        XCTAssertEqual(try history.importFlycut(data), 3)
        XCTAssertEqual(try history.importFlycut(data), 0)
        XCTAssertEqual(history.clips.filter(\.pinned).count, 2)
        XCTAssertEqual(history.clips.first { $0.text == "newest" }?.copiedAt, Date(timeIntervalSince1970: 1234))
        history.finishWrites()
        XCTAssertEqual(try History(directory: directory).clips, history.clips)
    }
    func testPausedChangesAreIgnoredAndManualCopyIsNotDuplicated() throws {
        let monitor = ClipboardMonitor(history: history, board: board)
        monitor.paused = true
        board.setString("not recorded", forType: .string); monitor.poll(app: "App")
        monitor.paused = false; monitor.poll(app: "App")
        XCTAssertTrue(history.clips.isEmpty)
        let clip = Clip(text: "chosen", app: "Source")
        XCTAssertTrue(monitor.copy(clip)); monitor.poll(app: "App")
        XCTAssertEqual(history.clips.map(\.text), ["chosen"])
        XCTAssertEqual(monitor.captured, 0)
        history.delete(try XCTUnwrap(history.clips.first?.id))
        history.finishWrites()
        XCTAssertTrue(try History(directory: directory).clips.isEmpty)
    }
    func testCorruptHistoryIsNeverOverwritten() throws {
        let file = directory.appendingPathComponent("history.json")
        let corrupt = Data("not JSON".utf8)
        try corrupt.write(to: file)
        XCTAssertThrowsError(try History(directory: directory))
        XCTAssertEqual(try Data(contentsOf: file), corrupt)
    }
}
