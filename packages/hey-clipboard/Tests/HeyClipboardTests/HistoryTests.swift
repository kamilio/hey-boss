import AppKit
import XCTest
@testable import HeyClipboard

final class HistoryTests: XCTestCase {
    private var directory: URL!
    private var history: History!
    private var board: NSPasteboard!
    override func setUpWithError() throws {
        directory = URL(fileURLWithPath: FileManager.default.currentDirectoryPath).appendingPathComponent(".build/clipboard-test-" + UUID().uuidString)
        history = try History(directory: directory)
        board = NSPasteboard.withUniqueName()
    }
    override func tearDownWithError() throws {
        history.finishWrites()
        board.releaseGlobally()
        try FileManager.default.removeItem(at: directory)
    }
    func testTemporaryDictationAndRestorationNeverEnterHistory() {
        board.setString("user copy", forType: .string)
        let monitor = ClipboardMonitor(history: history, board: board)
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            let item = NSPasteboardItem()
            item.setString("private dictation", forType: .string)
            item.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
            board.clearContents(); board.writeObjects([item])
            monitor.poll(app: "Hey Talk")
            board.clearContents(); board.setString("user copy", forType: .string)
            monitor.poll(app: "T3")
        }
        XCTAssertTrue(history.clips.isEmpty)
        XCTAssertEqual(monitor.skipped, 4)
        board.clearContents(); board.setString("new user copy 🌍\nline 2", forType: .string)
        monitor.poll(app: "T3")
        XCTAssertEqual(history.clips.map(\.text), ["new user copy 🌍\nline 2"])
    }
    func testMarkerOnSecondItemAlsoExcludesText() {
        let monitor = ClipboardMonitor(history: history, board: board)
        let text = NSPasteboardItem(), marker = NSPasteboardItem()
        text.setString("private", forType: .string)
        marker.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        board.writeObjects([text, marker]); monitor.poll(app: "Password manager")
        XCTAssertTrue(history.clips.isEmpty)
    }
    func testDeduplicationPinsRetentionAndPersistence() throws {
        let pinned = try XCTUnwrap(history.add("pinned", app: "App"))
        history.pin(pinned.id, true)
        for index in 0..<45 { history.add("entry \(index)", app: "App") }
        XCTAssertEqual(history.clips.count, 41)
        XCTAssertTrue(history.clips.contains { $0.id == pinned.id })
        let oldID = history.clips.first!.id
        history.add("entry 44", app: "App")
        XCTAssertEqual(history.clips.count, 41)
        XCTAssertEqual(history.clips.first?.id, oldID)
        history.finishWrites()
        let restored = try History(directory: directory)
        XCTAssertEqual(restored.clips, history.clips)
        XCTAssertEqual(restored.matching("ENTRY 44").count, 1)
        XCTAssertEqual(restored.matching("app").count, 41)
        let permissions = try FileManager.default.attributesOfItem(atPath: directory.appendingPathComponent("history.json").path)[.posixPermissions] as? Int
        XCTAssertEqual(permissions, 0o600)
    }
    func testFlycutMigrationIsIdempotentAndPreservesFavorites() throws {
        let data = try PropertyListSerialization.data(fromPropertyList: ["store": [
            "jcList": [["Contents": "newest", "AppLocalizedName": "Safari", "Timestamp": 1234], ["Contents": "older"]],
            "favoritesList": [["Contents": "older"], ["Contents": "favorite"]]
        ]], format: .binary, options: 0)
        XCTAssertEqual(try history.importFlycut(data), 3)
        XCTAssertEqual(try history.importFlycut(data), 0)
        XCTAssertEqual(history.clips.filter(\.pinned).count, 2)
        XCTAssertEqual(history.clips.first { $0.text == "newest" }?.copiedAt, Date(timeIntervalSince1970: 1234))
        history.finishWrites()
        XCTAssertEqual(try History(directory: directory).clips, history.clips)
    }
    func testPausedChangesAreIgnoredAndManualCopyIsNotDuplicated() throws {
        let monitor = ClipboardMonitor(history: history, board: board)
        monitor.paused = true
        board.setString("not recorded", forType: .string); monitor.poll(app: "App")
        monitor.paused = false; monitor.poll(app: "App")
        XCTAssertTrue(history.clips.isEmpty)
        let clip = Clip(text: "chosen", app: "Source")
        XCTAssertTrue(monitor.copy(clip)); monitor.poll(app: "App")
        XCTAssertEqual(history.clips.map(\.text), ["chosen"])
        XCTAssertEqual(monitor.captured, 0)
        history.delete(try XCTUnwrap(history.clips.first?.id))
        history.finishWrites()
        XCTAssertTrue(try History(directory: directory).clips.isEmpty)
    }
    func testCorruptHistoryIsNeverOverwritten() throws {
        let file = directory.appendingPathComponent("history.json")
        let corrupt = Data("not JSON".utf8)
        try corrupt.write(to: file)
        XCTAssertThrowsError(try History(directory: directory))
        XCTAssertEqual(try Data(contentsOf: file), corrupt)
    }
    func testBoundedPreviewKeepsFullTextForSearchAndCopy() throws {
        let text = String(repeating: "🌍", count: 300) + " searchable ending"
        let clip = try XCTUnwrap(history.add(text, app: "Test"))
        XCTAssertEqual(clip.preview, String(repeating: "🌍", count: 240))
        XCTAssertEqual(clip.summary["preview"] as? String, clip.preview)
        XCTAssertEqual(history.matching("searchable ending").first?.text, text)
        XCTAssertTrue(ClipboardMonitor(history: history, board: board).copy(clip))
        XCTAssertEqual(board.string(forType: .string), text)
    }
    func testPNGAndTIFFSurviveRestartAndCopyWithPinsAndDeduplication() throws {
        let bitmap = try XCTUnwrap(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 12, pixelsHigh: 8,
            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
        let monitor = ClipboardMonitor(history: history, board: board)
        for (type, format): (NSPasteboard.PasteboardType, NSBitmapImageRep.FileType) in [(.png, .png), (.tiff, .tiff)] {
            let data = try XCTUnwrap(bitmap.representation(using: format, properties: [:]))
            board.clearContents(); board.setData(data, forType: type)
            // Images copied from browsers can also offer a string; prefer the image.
            board.setString("image caption", forType: .string)
            monitor.poll(app: "Preview")
            let clip = try XCTUnwrap(history.clips.first)
            XCTAssertEqual(clip.imageType, type.rawValue)
            XCTAssertEqual(clip.preview, "Image")
            XCTAssertTrue(clip.text.isEmpty)
            XCTAssertNotNil(history.thumbnail(clip))
            XCTAssertEqual(try Data(contentsOf: history.imageURL(clip)), data)
            XCTAssertEqual(try FileManager.default.attributesOfItem(atPath: history.imageURL(clip).path)[.posixPermissions] as? Int, 0o600)
            history.pin(clip.id, true)
            history.finishWrites()
            let restored = try History(directory: directory)
            XCTAssertEqual(restored.clips, history.clips)
            board.clearContents(); board.setString("other text", forType: .string)
            let restoredMonitor = ClipboardMonitor(history: restored, board: board)
            XCTAssertTrue(restoredMonitor.copy(try XCTUnwrap(restored.clips.first)))
            XCTAssertEqual(board.data(forType: type), data)
            XCTAssertNil(board.string(forType: .string))
            restoredMonitor.poll(app: "Destination")
            XCTAssertEqual(restored.clips.first?.id, clip.id)
            XCTAssertEqual(restored.clips.first?.pinned, true)
            restored.finishWrites()
            board.clearContents(); board.setString("intervening text", forType: .string); monitor.poll(app: "Test")
            board.clearContents(); board.setData(data, forType: type); monitor.poll(app: "Preview")
            XCTAssertEqual(history.clips.first?.id, clip.id)
            XCTAssertEqual(history.clips.filter { $0.imageType == type.rawValue }.count, 1)
        }
    }
    func testExcludedImagesAndRestorationDoNotEnterHistory() throws {
        let image = Data([1, 2, 3])
        board.setData(image, forType: .png)
        let monitor = ClipboardMonitor(history: history, board: board)
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType", "PasswordPboardType", "com.agilebits.onepassword"] {
            board.clearContents(); board.setData(Data([4, 5, 6]), forType: .png)
            board.setData(Data(), forType: NSPasteboard.PasteboardType(marker)); monitor.poll(app: "Private")
            board.clearContents(); board.setData(image, forType: .png); monitor.poll(app: "Restored")
        }
        XCTAssertTrue(history.clips.isEmpty)
        XCTAssertEqual(monitor.skipped, 5)
        monitor.paused = true
        board.clearContents(); board.setData(Data([7]), forType: .png); monitor.poll(app: "Paused")
        monitor.paused = false; monitor.poll(app: "Resumed")
        XCTAssertTrue(history.clips.isEmpty)
    }
    func testImageRetentionDeletionAndClearRemoveFilesButKeepPins() throws {
        let pinned = try XCTUnwrap(history.add(Data([1]), type: .png, app: "Test"))
        history.pin(pinned.id, true)
        let evicted = try XCTUnwrap(history.add(Data([2]), type: .png, app: "Test"))
        for index in 0..<40 { history.add("text \(index)", app: "Test") }
        history.finishWrites()
        XCTAssertTrue(FileManager.default.fileExists(atPath: history.imageURL(pinned).path))
        XCTAssertFalse(FileManager.default.fileExists(atPath: history.imageURL(evicted).path))
        history.delete(pinned.id); history.finishWrites()
        XCTAssertFalse(FileManager.default.fileExists(atPath: history.imageURL(pinned).path))
        let cleared = try XCTUnwrap(history.add(Data([3]), type: .tiff, app: "Test"))
        history.clear(); history.finishWrites()
        XCTAssertFalse(FileManager.default.fileExists(atPath: history.imageURL(cleared).path))
        XCTAssertTrue(try History(directory: directory).clips.isEmpty)
    }
    func testMissingImageNeverClearsClipboardAndOldTextHistoryStillLoads() throws {
        let clip = try XCTUnwrap(history.add(Data([1]), type: .png, app: "Test"))
        try FileManager.default.removeItem(at: history.imageURL(clip))
        board.setString("keep me", forType: .string)
        XCTAssertFalse(ClipboardMonitor(history: history, board: board).copy(clip))
        XCTAssertEqual(board.string(forType: .string), "keep me")
        history.finishWrites()
        let old = """
        [{"id":"\(UUID().uuidString)","text":"old text","app":"Safari","copiedAt":0,"pinned":true}]
        """
        try Data(old.utf8).write(to: directory.appendingPathComponent("history.json"))
        let restored = try History(directory: directory)
        XCTAssertEqual(restored.clips.first?.text, "old text")
        XCTAssertEqual(restored.clips.first?.pinned, true)
        XCTAssertNil(restored.clips.first?.imageType)
    }
}
