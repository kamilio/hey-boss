async page => {
  await page.reload();
  const fixture=await page.evaluate(async()=>{
    const project=new URLSearchParams(location.hash.slice(1)).get('project');
    return {project,issue:'1',origin:location.origin};
  });
  const title='Issue-created plan '+Date.now();
  const updatedTitle='Updated '+title;
  const issueURL=fixture.origin+'/#project='+encodeURIComponent(fixture.project)+'&issue='+fixture.issue;
  await page.goto(issueURL);
  await page.locator('#issue-artifacts a').filter({hasText:'Renamed browser plan'}).waitFor();
  await page.locator('#issue-artifacts a').filter({hasText:'Renamed browser plan'}).click();
  await page.locator('.artifact-backlinks a').filter({hasText:'#1'}).waitFor();
  await page.locator('.artifact-backlinks a').filter({hasText:'#1'}).click();
  await page.locator('#issue-artifacts a').filter({hasText:'Create artifact'}).waitFor();
  await page.locator('#issue-artifacts a').filter({hasText:'Create artifact'}).click();
  const context=await page.evaluate(()=>Object.fromEntries(new URLSearchParams(location.hash.slice(1))));
  if(context.project!==fixture.project||context.issue!==fixture.issue)throw Error('Issue creation lost resource project');
  await page.getByRole('textbox',{name:'Title',exact:true}).fill(title);
  await page.getByRole('textbox',{name:'Markdown',exact:true}).fill('# Shared issue document');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.locator('.artifact-backlinks a').filter({hasText:'#1'}).waitFor();
  const documentURL=page.url();
  await page.locator('.artifact-backlinks a').filter({hasText:'#1'}).click();
  await page.locator('#issue-artifacts a').filter({hasText:title}).waitFor();
  await page.getByRole('button',{name:'Unlink '+title,exact:true}).click();
  await page.getByRole('button',{name:'Attach existing',exact:true}).click();
  await page.getByRole('searchbox',{name:'Find artifact to attach',exact:true}).fill('no-matching-attachment');
  await page.getByText('No matching artifacts',{exact:true}).waitFor();
  if(!await page.getByRole('button',{name:'Attach',exact:true}).isDisabled())throw Error('Empty attachment search leaves Attach enabled');
  await page.getByRole('button',{name:'Cancel attachment',exact:true}).click();
  if(await page.getByRole('searchbox',{name:'Find artifact to attach',exact:true}).count())throw Error('Cancel leaves the attachment picker open');
  await page.getByRole('button',{name:'Attach existing',exact:true}).click();
  await page.getByRole('searchbox',{name:'Find artifact to attach',exact:true}).fill(title);
  await page.waitForFunction(()=>document.querySelector('[aria-label="Artifact to attach"]')?.options.length===1);
  await page.getByRole('button',{name:'Attach',exact:true}).click();
  await page.locator('#issue-artifacts a').filter({hasText:title}).waitFor();
  await page.locator('#issue-artifacts a').filter({hasText:title}).click();
  if(page.url()!==documentURL)throw Error('Reattachment copied the document');
  await page.locator('.artifact-backlinks a').filter({hasText:'#1'}).waitFor();
  const identity=await page.evaluate(()=>new URLSearchParams(location.hash.slice(1)).get('artifact'));
  await page.goto(issueURL);
  await page.locator('#issue-artifacts a').filter({hasText:title}).waitFor();
  await page.evaluate(async({project,identity,updatedTitle})=>{
    const boot=await(await fetch('/api/bootstrap')).json();
    const response=await fetch('/api/action',{method:'POST',headers:{'Content-Type':'application/json','X-Hey-Boss-CSRF':boot.csrf},body:JSON.stringify({project,operation:{action:'artifact',operation:{command:'edit',id:identity,title:updatedTitle,if_version:1}}})});
    if(!response.ok)throw Error(await response.text());
  },{project:fixture.project,identity,updatedTitle});
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.locator('#issue-artifacts a').filter({hasText:updatedTitle}).waitFor();
  return {shared_issue_target:true,automatic_project:true,unlink_preserves_document:true,attach_reuses_identity:true,refresh_updates_references:true};
}
