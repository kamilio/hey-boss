// Start both worker fixture servers, then run with playwright-cli run-code --filename.
async page => {
  const checks=[],errors=[];
  const check=(condition,label)=>{if(!condition)throw Error(label);checks.push(label);};
  page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:1440,height:1050});
  await page.goto('http://127.0.0.1:59688/workers');
  await page.locator('.project-worker-machine').first().waitFor();
  check(await page.locator('.project-worker').count()===7,'Stopped history and independent workers stay out of project workers');
  check(await page.locator('.worker-scope-group').count()===0,'Project workers have no extra grouping layer');
  check(await page.locator('.project-worker-task:visible').count()===4,'Current tasks are directly visible');
  await page.locator('.project-worker-task').first().focus();
  await page.waitForTimeout(3300);
  check(await page.locator('.project-worker-task').first().evaluate(el=>document.activeElement===el),'Refresh preserves the focused task link');
  await page.locator('[data-activity-filter="busy"]').click();
  check(await page.locator('.project-worker').count()===2,'Working filter shows project workers doing work');
  await page.locator('[data-activity-filter="all"]').click();
  await page.locator('#worker-search').fill('keyboard navigation');
  check(await page.locator('.project-worker').count()===1,'Search finds current tasks');
  await page.locator('#worker-search').fill('');
  for(const width of [1440,390,320]){
    await page.setViewportSize({width,height:844});
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),width+'px fits');
  }
  await page.setViewportSize({width:1440,height:1050});
  await page.goto('http://127.0.0.1:59648/workers#view=configuration',{waitUntil:'domcontentloaded'});
  await page.locator('[data-edit-worker="tools"]').click();
  await page.locator('#worker-editor').waitFor({state:'visible'});
  await page.locator('#worker-slots').fill('0');
  check(!await page.locator('#worker-slots').evaluate(el=>el.checkValidity()),'Structured form rejects zero slots');
  await page.locator('#worker-slots').fill('3');
  await page.locator('#worker-name').fill('Review worker');
  await page.locator('#worker-editor-preview').click();
  await page.waitForFunction(()=>!document.getElementById('worker-editor-save').disabled);
  check((await page.locator('#worker-editor-changes').innerText()).includes('2 → 3'),'Review shows the exact slot change');
  await page.screenshot({path:'output/playwright/workers-structure/settings-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Structured form fits on a phone');
  await page.screenshot({path:'output/playwright/workers-structure/settings-phone.png',fullPage:true});
  await page.locator('#worker-editor-save').click();
  await page.locator('#worker-editor').waitFor({state:'hidden'});
  const saved=await page.evaluate(()=>fetch('/api/fleet/configuration').then(r=>r.json()));
  check(saved.document.machines.local.workers[0].config.concurrency===3&&saved.document.machines.local.workers[0].config.name==='Review worker','Form writes the worker settings to authoritative YAML');
  await page.locator('[data-edit-worker="tools"]').click();
  await page.locator('#worker-editor').waitFor({state:'visible'});
  await page.locator('#worker-name').fill('Unsaved draft');
  const external=await page.evaluate(async c=>{const bootstrap=await fetch('/api/bootstrap').then(r=>r.json());return fetch('/api/fleet/configuration',{method:'POST',headers:{'Content-Type':'application/json','X-Hey-Boss-CSRF':bootstrap.csrf},body:JSON.stringify({text:c.text+'# external edit\n',revision:c.revision,save:true})}).then(r=>r.json());},saved);
  check(external.ok,'External fixture edit succeeded');
  await page.locator('#worker-editor-preview').click();
  await page.waitForFunction(()=>document.getElementById('worker-editor-status').textContent.includes('changed'));
  check(await page.locator('#worker-name').inputValue()==='Unsaved draft'&&await page.locator('#worker-editor-save').isDisabled(),'Stale form retains its draft and blocks saving');
  await page.locator('#worker-name').fill('Review worker');
  await page.locator('#worker-editor-cancel').click();
  await page.locator('#config-editor>summary').click();
  await page.waitForFunction(()=>!document.getElementById('config-text').disabled);
  const original=await page.locator('#config-text').inputValue();
  await page.locator('#config-text').fill('machines: [');
  await page.locator('#config-validate').click();
  await page.waitForFunction(()=>!document.getElementById('config-validate').disabled);
  check(await page.locator('#config-save').isDisabled(),'Advanced YAML still validates before saving');
  await page.locator('#config-text').fill(original);
  check(errors.length===0,'No browser JavaScript errors');
  return {passed:checks.length,checks};
}
