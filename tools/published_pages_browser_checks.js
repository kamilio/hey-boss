// Run against a private fixture with a five-file "weekly-report" site.
async page => {
  const checks = [], errors = [];
  const check = (ok, name) => { if (!ok) throw Error(name); checks.push(name); };
  page.on('pageerror', e => errors.push(e.message));
  const origin = new URL(page.url()).origin;
  await page.goto(origin + '/pages');
  await page.getByRole('heading', {name:'weekly-report',exact:true}).waitFor();
  await page.getByRole('button', {name:'More global destinations',exact:true}).click();
  check(await page.locator('#navigation-more-links #nav-pages').isVisible(), 'Published Pages lives in global overflow');
  check(await page.locator('.app-navigation #nav-pages').count() === 0, 'Project tabs do not contain Published Pages');
  check(await page.locator('#nav-pages').getAttribute('href') === '/pages', 'Global link has no project selector');
  await page.keyboard.press('Escape');
  check(await page.locator('.page-card').count() > 0, 'Private library shows published pages');
  await page.screenshot({path:'out/publish-checks/library-desktop.png',fullPage:true});
  await page.getByRole('heading', {name:'weekly-report',exact:true}).click();
  const frame = page.frameLocator('#page-frame');
  await frame.locator('#result').filter({hasText:'A private page'}).waitFor();
  await frame.locator('#counter').click();
  check(await frame.locator('#counter').textContent() === 'Try it · 1', 'JavaScript modules and interactions work in the iframe');
  check(await frame.locator('body').evaluate(e => getComputedStyle(e).backgroundColor) === 'rgb(247, 244, 236)', 'Relative CSS asset loads');
  const sandbox = await frame.locator('body').evaluate(() => window.sandboxCheck);
  check(sandbox.blocked === true, 'Published scripts cannot read the parent hey-boss document');
  check(await page.locator('#page-frame').getAttribute('sandbox').then(s=>!s.includes('allow-same-origin')), 'Iframe remains an opaque origin');
  await page.screenshot({path:'out/publish-checks/viewer-desktop.png',fullPage:true});
  await frame.getByRole('link',{name:'Read more'}).click();
  await frame.getByRole('heading',{name:'Nested page'}).waitFor();
  check(true, 'Nested directory index and relative navigation work');
  await frame.getByRole('link',{name:'Back'}).click();
  await frame.locator('#counter').waitFor();
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), 'Mobile viewer has no horizontal overflow');
  await page.screenshot({path:'out/publish-checks/viewer-mobile.png',fullPage:true});
  await page.goto(origin+'/pages');
  await page.getByRole('heading',{name:'weekly-report',exact:true}).waitFor();
  await page.emulateMedia({colorScheme:'dark'});
  check(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), 'Mobile library has no horizontal overflow');
  await page.screenshot({path:'out/publish-checks/library-mobile-dark.png',fullPage:true});
  await page.getByRole('button',{name:'Delete weekly-report',exact:true}).click();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  check(await page.getByRole('heading',{name:'weekly-report',exact:true}).count()===1, 'Cancelling deletion preserves the page');
  await page.getByRole('button',{name:'Delete weekly-report',exact:true}).click();
  await page.getByRole('button',{name:'Delete page',exact:true}).click();
  await page.getByRole('heading',{name:'weekly-report',exact:true}).waitFor({state:'detached'});
  await page.goto(origin+'/pages/weekly-report');
  await page.locator('#pages-error').filter({hasText:'not found'}).waitFor();
  check(await page.locator('#page-frame').isHidden(), 'Deleted page cannot be opened');
  check(errors.length===0,'No uncaught JavaScript errors: '+errors.join('; '));
  return {passed:checks.length,checks};
}
